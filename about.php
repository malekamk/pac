      <h2>Johannesburg Region Today</h2>
      <p>The PAC&rsquo;s head office sits in the heart of Johannesburg at Khotso House on Marshal Street &mdash; historically a hub of the liberation movement. From here, the Johannesburg Region organises branches across the city, runs the Pan Africanist Youth Congress of Azania (PAYCO) and the Pan Africanist Women&rsquo;s Organisation (PAWO), and is campaigning under mayoral candidate Thami ka Plaatjie to end maladministration and delayed service delivery in the City of Johannesburg ahead of the 2026 Local Government Elections.</p>
