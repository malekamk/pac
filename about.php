      <span class="eyebrow">Our History</span>
      <h2>Izwe Lethu &mdash; Our Land</h2>
      <p>The Pan Africanist Congress of Azania (PAC) was launched on 6 April 1959 at the Orlando Community Hall in Soweto. It emerged from an Africanist bloc inside the ANC Youth League &mdash; among them Anton Lembede, A.P. Mda, Potlako Leballo and Robert Mangaliso Sobukwe &mdash; who rejected the ANC&rsquo;s multiracialist Freedom Charter position that &ldquo;the land belongs to all who live in it, both black and white.&rdquo; Sobukwe was elected the PAC&rsquo;s founding President and Potlako Leballo its Secretary-General.</p>

