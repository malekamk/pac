      <h2>Ideology &amp; Identity</h2>
      <p>The PAC stands for Africanism: the view, in Sobukwe&rsquo;s words, that &ldquo;there is only one race to which we all belong &mdash; the human race,&rdquo; and that in a free Azania sovereignty rests with the African majority who were dispossessed of their land. The party&rsquo;s colours are <strong>black, green and gold</strong>, and its enduring rallying cry is <strong>Izwe Lethu!!</strong> &mdash; Our Land!!</p>
