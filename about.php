      <h2>Timeline</h2>
      <div class="timeline">
        <div class="item"><span class="yr">1959</span><p>PAC founded at Orlando Community Hall, Soweto. Robert Sobukwe elected founding President on an Africanist platform of &ldquo;Africa for the Africans,&rdquo; under the slogan <em>Izwe Lethu!!</em> (Our Land!!).</p></div>
        <div class="item"><span class="yr">21 March 1960</span><p>The PAC launches the Anti-Pass Campaign. In Sharpeville, police open fire on unarmed protesters, killing 69 people and injuring 180 &mdash; the Sharpeville Massacre.</p></div>
        <div class="item"><span class="yr">8 April 1960</span><p>The apartheid government bans both the PAC and the ANC. Sobukwe and Leballo are arrested; thousands of members are detained or forced into exile.</p></div>
        <div class="item"><span class="yr">1960s&ndash;1980s</span><p>The PAC establishes its armed wing, the Azanian People&rsquo;s Liberation Army (APLA), and continues the struggle from exile and underground, including involvement around the 1976 Soweto uprising.</p></div>
        <div class="item"><span class="yr">1990</span><p>The PAC is unbanned as apartheid negotiations begin, and returns to legal political activity inside the country.</p></div>
        <div class="item"><span class="yr">1994</span><p>In South Africa&rsquo;s first democratic election, the PAC wins 5 seats in the National Assembly (1.25% of the vote).</p></div>
        <div class="item"><span class="yr">2024</span><p>President Mzwanele Nyhontso is sworn in as Minister of Land Reform and Rural Development in the Government of National Unity.</p></div>
        <div class="item"><span class="yr">2026</span><p>The PAC names Thami ka Plaatjie as its candidate for Executive Mayor of Johannesburg ahead of the 4 November Local Government Elections.</p></div>
